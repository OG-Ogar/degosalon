create function degosalon_internal.canonical_barber_location() returns trigger
 language plpgsql set search_path = '' as $$
declare original_state text := new.state;
begin
 new.state_id := null; new.local_area_id := null;
 select s.id,s.name into new.state_id,new.state
 from degosalon_internal.geography_state_aliases x join degosalon_internal.geography_states s on s.id=x.state_id
 where x.alias=pg_catalog.regexp_replace(pg_catalog.lower(new.state),'[^a-z0-9]','','g');
 -- SELECT INTO sets missing values to null; preserve the submitted legacy text.
 if new.state_id is null then new.state := original_state; return new; end if;
 select a.id into new.local_area_id from degosalon_internal.geography_area_aliases x
 join degosalon_internal.geography_areas a on a.id=x.area_id
 where x.state_id=new.state_id and x.alias=pg_catalog.regexp_replace(pg_catalog.lower(new.local_area),'[^a-z0-9]','','g');
 if new.local_area_id is not null then
  select a.name into new.local_area from degosalon_internal.geography_areas a where a.id=new.local_area_id;
 end if;
 return new;
end;
$$;
revoke all on function degosalon_internal.canonical_barber_location() from public;
create trigger canonical_barber_location before insert or update of state,local_area,state_id,local_area_id on public.barbers for each row execute function degosalon_internal.canonical_barber_location();
