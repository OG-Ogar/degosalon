create table public.social_posts (
 id bigint generated by default as identity primary key,
 author_role text not null check (author_role in ('customer','barber')),
 customer_id bigint references public.customers(id) on delete cascade,
 barber_id bigint references public.barbers(id) on delete cascade,
 body text not null default '' check (char_length(body) <= 2000),
 text_color text not null default '#0c1524' check (text_color ~ '^#[0-9a-fA-F]{6}$'),
 text_style text not null default 'normal' check (text_style in ('normal','bold','italic')),
 image text not null default '',
 video text not null default '',
 created_at timestamptz not null default now(),
 check ((author_role='customer' and customer_id is not null and barber_id is null)
     or (author_role='barber' and barber_id is not null and customer_id is null)),
 check (image='' or video=''),
 check (length(trim(body))>0 or image<>'' or video<>'')
);
create index social_posts_created_idx on public.social_posts(created_at desc,id desc);
alter table public.social_posts enable row level security;
create trigger guard_social_post_media before insert or update of image,video on public.social_posts
    for each row execute function degosalon_internal.guard_media_reference('image','video');

create table public.social_post_likes (
 post_id bigint not null references public.social_posts(id) on delete cascade,
 customer_id bigint references public.customers(id) on delete cascade,
 barber_id bigint references public.barbers(id) on delete cascade,
 created_at timestamptz not null default now(),
 check ((customer_id is not null and barber_id is null) or (barber_id is not null and customer_id is null))
);
create unique index social_post_customer_like_unique on public.social_post_likes(post_id,customer_id) where customer_id is not null;
create unique index social_post_barber_like_unique on public.social_post_likes(post_id,barber_id) where barber_id is not null;
create index social_post_likes_post_idx on public.social_post_likes(post_id);
alter table public.social_post_likes enable row level security;

create table public.social_post_comments (
 id bigint generated by default as identity primary key,
 post_id bigint not null references public.social_posts(id) on delete cascade,
 author_role text not null check (author_role in ('customer','barber')),
 customer_id bigint references public.customers(id) on delete cascade,
 barber_id bigint references public.barbers(id) on delete cascade,
 body text not null check (char_length(body) between 1 and 500 and length(trim(body))>0),
 created_at timestamptz not null default now(),
 check ((author_role='customer' and customer_id is not null and barber_id is null)
     or (author_role='barber' and barber_id is not null and customer_id is null))
);
create index social_post_comments_post_idx on public.social_post_comments(post_id,created_at,id);
alter table public.social_post_comments enable row level security;
