-- Browser Web Push registrations used when the recipient has closed the app.
-- One account may have several devices. Endpoint is unique because a browser
-- that signs in to another account should move its registration rather than
-- receive the previous account's notifications as well.
create table if not exists degosalon_internal.push_subscriptions (
    id bigint generated by default as identity primary key,
    user_role text not null check (user_role in ('barber','customer')),
    user_id bigint not null check (user_id > 0),
    endpoint text not null unique,
    p256dh text not null,
    auth text not null,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);
create index if not exists push_subscriptions_owner_idx
    on degosalon_internal.push_subscriptions(user_role,user_id);
revoke all on degosalon_internal.push_subscriptions from public;
alter table degosalon_internal.push_subscriptions enable row level security;
