-- Barber Booking persistent schema for Supabase Postgres.
-- The Go backend connects directly to Postgres.
-- RLS is enabled on every public table so the automatically exposed
-- Data API denies anon/authenticated access by default.

create table if not exists public.barbers (
  id bigint generated by default as identity primary key,
  full_name text not null,
  phone_number text not null,
  email text not null unique,
  password_hash text not null,
  shop_name text not null,
  shop_address text not null,
  state text not null default '',
  local_area text not null default '',
  profile_image text not null default '',
  personal_image text not null default '',
  status text not null default 'Active'
    check (status in ('Active', 'Suspended'))
);

create table if not exists public.customers (
  id bigint generated by default as identity primary key,
  full_name text not null,
  phone_number text not null,
  email text not null unique,
  password_hash text not null,
  profile_image text not null default ''
);

create table if not exists public.hairstyles (
  id bigint generated by default as identity primary key,
  barber_id bigint not null references public.barbers(id) on delete cascade,
  name text not null,
  category text not null,
  description text not null default '',
  price numeric(12,2) not null check (price >= 0),
  duration integer not null check (duration > 0),
  image text not null default '',
  video text not null default '',
  is_available boolean not null default true
);

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  barber_id bigint not null references public.barbers(id) on delete cascade,
  name text not null,
  category text not null,
  description text not null default '',
  price numeric(12,2) not null check (price >= 0),
  quantity integer not null default 0 check (quantity >= 0),
  image text not null default '',
  is_available boolean not null default true
);

create table if not exists public.bookings (
  id bigint generated by default as identity primary key,
  barber_id bigint not null references public.barbers(id) on delete cascade,
  hairstyle_id bigint not null references public.hairstyles(id),
  customer_id bigint not null references public.customers(id) on delete cascade,
  customer_name text not null,
  customer_phone text not null,
  customer_email text not null,
  booking_date date not null,
  booking_time time not null,
  notes text not null default '',
  status text not null default 'Pending'
    check (
      status in (
        'Pending',
        'Accepted',
        'Rejected',
        'Cancelled',
        'Completed'
      )
    ),
  created_at timestamptz not null default now()
);

create unique index if not exists bookings_open_slot_unique
  on public.bookings (barber_id, booking_date, booking_time)
  where status in ('Pending', 'Accepted', 'Completed');

create table if not exists public.messages (
  id bigint generated by default as identity primary key,
  barber_id bigint not null references public.barbers(id) on delete cascade,
  customer_id bigint not null references public.customers(id) on delete cascade,
  sender_role text not null
    check (sender_role in ('barber', 'customer')),
  sender_name text not null,
  text text not null,
  image text not null default '',
  audio text not null default '',
  sent_at timestamptz not null default now()
);

-- Add media columns to an existing messages table if they are missing.
-- Existing messages are preserved, and their new fields default to empty strings.

alter table public.messages
  add column if not exists image text not null default '';

alter table public.messages
  add column if not exists audio text not null default '';

create table if not exists public.carts (
  customer_id bigint not null references public.customers(id) on delete cascade,
  product_id bigint not null references public.products(id) on delete cascade,
  quantity integer not null check (quantity > 0),
  primary key (customer_id, product_id)
);

create table if not exists public.product_orders (
  id bigint generated by default as identity primary key,
  customer_id bigint not null references public.customers(id) on delete cascade,
  customer_name text not null,
  customer_phone text not null,
  customer_email text not null,
  total_amount numeric(12,2) not null check (total_amount >= 0),
  status text not null default 'Pending'
    check (status in ('Pending', 'Paid', 'Cancelled', 'Completed')),
  created_at timestamptz not null default now()
);

create table if not exists public.product_order_items (
  id bigint generated by default as identity primary key,
  order_id bigint not null references public.product_orders(id) on delete cascade,
  product_id bigint not null references public.products(id),
  barber_id bigint not null references public.barbers(id),
  product_name text not null,
  price numeric(12,2) not null check (price >= 0),
  quantity integer not null check (quantity > 0),
  subtotal numeric(12,2) not null check (subtotal >= 0)
);

create table if not exists public.reviews (
  id bigint generated by default as identity primary key,
  barber_id bigint not null references public.barbers(id) on delete cascade,
  customer_id bigint not null references public.customers(id) on delete cascade,
  booking_id bigint not null unique references public.bookings(id) on delete cascade,
  customer_name text not null,
  rating integer not null check (rating between 1 and 5),
  comment text not null default '',
  created_at timestamptz not null default now()
);

-- Indexes

create index if not exists barbers_location_idx
  on public.barbers(state, local_area);

create index if not exists reviews_barber_idx
  on public.reviews(barber_id, created_at desc);

create index if not exists hairstyles_barber_idx
  on public.hairstyles(barber_id);

create index if not exists products_barber_idx
  on public.products(barber_id);

create index if not exists bookings_barber_idx
  on public.bookings(barber_id);

create index if not exists bookings_customer_idx
  on public.bookings(customer_id);

create index if not exists messages_conversation_idx
  on public.messages(barber_id, customer_id, sent_at);

create index if not exists product_orders_customer_idx
  on public.product_orders(customer_id);

create index if not exists product_order_items_order_idx
  on public.product_order_items(order_id);

-- Row Level Security

alter table public.barbers enable row level security;
alter table public.customers enable row level security;
alter table public.hairstyles enable row level security;
alter table public.products enable row level security;
alter table public.bookings enable row level security;
alter table public.messages enable row level security;
alter table public.carts enable row level security;
alter table public.product_orders enable row level security;
alter table public.product_order_items enable row level security;
alter table public.reviews enable row level security;